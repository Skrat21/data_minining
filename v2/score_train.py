#!/usr/bin/env python3
"""Score the fixed MGB-2 subset and flag its worst ten percent by WER."""

from __future__ import annotations

import argparse
import random
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import numpy as np  # noqa: E402

from evaluate_model import (  # noqa: E402
    compute_per_utterance_metrics,
    transcribe_records,
)
from v2.mgb2_common import (  # noqa: E402
    FLAG_FRACTION,
    RUNS_DIR,
    append_notes,
    gpu_preflight,
    load_jsonl,
    load_inference_model,
    worst_fraction_ids,
    write_json,
    write_jsonl,
)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", required=True, help="A0 final or selected checkpoint")
    parser.add_argument(
        "--processor-path",
        default=None,
        help="Tokenizer/processor directory; use A0 final_model when scoring a checkpoint",
    )
    parser.add_argument(
        "--subset",
        default=str(RUNS_DIR / "data" / "train_subset_seed123.jsonl"),
    )
    parser.add_argument("--output-dir", default=str(RUNS_DIR / "scoring" / "A0"))
    parser.add_argument("--batch-size", type=int, default=4)
    parser.add_argument("--max-new-tokens", type=int, default=225)
    parser.add_argument("--num-workers", type=int, default=4)
    args = parser.parse_args()
    if args.batch_size <= 0 or args.num_workers < 0:
        raise ValueError("Batch size must be positive and worker count non-negative")
    if not 1 <= args.max_new_tokens <= 448:
        raise ValueError("--max-new-tokens must be between 1 and 448")

    started = time.perf_counter()
    gpu_preflight(args.output_dir)
    records = load_jsonl(args.subset)
    if not records:
        raise ValueError(f"Subset is empty: {args.subset}")

    processor, model, _ = load_inference_model(
        args.model, processor_path=args.processor_path, fp16=True
    )
    hypotheses, decode_seconds = transcribe_records(
        model,
        processor,
        records,
        batch_size=args.batch_size,
        max_new_tokens=args.max_new_tokens,
        language="ar",
        num_workers=args.num_workers,
        desc="Score MGB-2 A0 subset",
    )
    per_utterance = compute_per_utterance_metrics(
        hypotheses,
        [r["text_norm"] for r in records],
        [r["id"] for r in records],
        records,
    )
    compact_scores = [
        {
            "id": row["id"],
            "ref": row["ref"],
            "hyp": row["hyp"],
            "wer": row["wer"],
            "cer": row["cer"],
            "word_errors": row["word_errors"],
            "ref_words": row["ref_words"],
        }
        for row in per_utterance
    ]
    flagged_ids, cutoff_wer = worst_fraction_ids(compact_scores, FLAG_FRACTION)
    flagged_set = set(flagged_ids)
    wers = np.asarray([row["wer"] for row in compact_scores], dtype=np.float64)
    absolute_errors = np.asarray(
        [row["word_errors"] for row in compact_scores], dtype=np.int64
    )
    total_clips = len(compact_scores)
    short_flagged = sum(
        row["ref_words"] < 3 and row["id"] in flagged_set
        for row in compact_scores
    )

    output = Path(args.output_dir)
    output.mkdir(parents=True, exist_ok=True)
    write_jsonl(output / "train_scores.jsonl", compact_scores)
    (output / "flagged_ids.txt").write_text(
        "".join(f"{uid}\n" for uid in flagged_ids), encoding="utf-8"
    )
    rng = random.Random(123)
    flagged_rows = [row for row in compact_scores if row["id"] in flagged_set]
    non_flagged_rows = [row for row in compact_scores if row["id"] not in flagged_set]
    sample_count = min(50, len(flagged_rows), len(non_flagged_rows))
    sample_path = Path(__file__).with_name("flagged_sample.md")
    sample_parts = [
        "# MGB-2 A0 training-set score sample",
        "",
        "Random examples for human review; generated by `score_train.py` with seed 123.",
        "A1 selection uses the worst 10% by per-utterance WER, not Common Voice's",
        "WER >= 1.0 rule.",
        "",
    ]
    for title, pool in (
        ("Flagged examples", flagged_rows),
        ("Non-flagged examples", non_flagged_rows),
    ):
        sample_parts.extend([f"## {title}", ""])
        for row in rng.sample(pool, sample_count):
            sample_parts.extend(
                [
                    f"### `{row['id']}` - WER {row['wer']}",
                    "",
                    f"- Reference: {row['ref']}",
                    f"- A0 hypothesis: {row['hyp']}",
                    "",
                ]
            )
    sample_path.write_text("\n".join(sample_parts), encoding="utf-8")
    summary = {
        "model": str(Path(args.model).resolve()),
        "subset_manifest": str(Path(args.subset).resolve()),
        "flag_rule": "worst 10% by per-utterance WER",
        "flag_fraction": FLAG_FRACTION,
        "scoring_decode": {
            "language": "ar",
            "task": "transcribe",
            "num_beams": 1,
            "max_new_tokens": args.max_new_tokens,
            "no_repeat_ngram_size": None,
            "loop_trimming": False,
        },
        "total_clips": total_clips,
        "flagged_count": len(flagged_ids),
        "flagged_fraction": len(flagged_ids) / total_clips,
        "flagged_count_wer_ge_1": int(np.sum(wers >= 1.0)),
        "flagged_fraction_wer_ge_1": float(np.mean(wers >= 1.0)),
        "worst_10pct_cutoff_wer": cutoff_wer,
        "flagged_fewer_than_3_reference_words": int(short_flagged),
        "flagged_sample_markdown": str(sample_path.resolve()),
        "flagged_sample_per_group": sample_count,
        "per_utterance_wer_percentiles": {
            str(q): float(np.percentile(wers, q))
            for q in (0, 25, 50, 75, 90, 95, 99, 100)
        },
        "word_error_count_percentiles": {
            str(q): float(np.percentile(absolute_errors, q))
            for q in (0, 50, 90, 99, 100)
        },
        "decode_seconds": round(decode_seconds, 3),
        "total_wall_seconds": round(time.perf_counter() - started, 3),
    }
    write_json(output / "scoring_summary.json", summary)
    append_notes(
        "### A0 subset scoring\n\n"
        f"- Model: `{Path(args.model).resolve()}`; clips: {total_clips}; "
        f"flagged by worst-10% rule: {len(flagged_ids)}.\n"
        f"- Decode time: {decode_seconds:.1f} s; total wall time: "
        f"{summary['total_wall_seconds']:.1f} s. Sample: "
        f"`{sample_path.resolve()}`.\n"
    )
    print(summary)


if __name__ == "__main__":
    main()
